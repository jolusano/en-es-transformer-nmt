def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=None)
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument(
        "--primary", default="bpe_scratch",
        help="run whose error analysis and examples go in the appendix",
    )
    args = parser.parse_args()

    setup_logging()
    root = project_root()
    results_dir = args.results or root / "artifacts" / "results"
    output_dir = ensure_dir(args.output or root / "reports" / "final_report" / "generated")

    macros = MacroFile()

    # --- dataset ----------------------------------------------------------
    stats_path = results_dir / "dataset_stats.json"
    if stats_path.exists():
        stats = read_json(stats_path)
        (output_dir / "tab_dataset.tex").write_text(
            dataset_table(stats, macros), encoding="utf-8"
        )
        logger.info("tab_dataset.tex")
    else:
        logger.warning("No dataset_stats.json; run `python -m nmt.data.build` first.")

    # --- embedding coverage ----------------------------------------------
    embedding_path = results_dir / "embedding_init_report.json"
    if embedding_path.exists():
        report = read_json(embedding_path)
        macros.number("muse coverage percent", report["covered_fraction"] * 100, decimals=1)
        macros.integer("muse covered", report["covered"])
        macros.integer("muse random", report["randomly_initialised"])

    # --- models and training ---------------------------------------------
    summaries: dict[str, dict] = {}
    reports: dict[str, dict] = {}
    for directory in sorted(p for p in results_dir.iterdir() if p.is_dir()):
        summary_path = directory / "training_summary.json"
        if summary_path.exists():
            summary = read_json(summary_path)
            if summary.get("history"):
                summaries[directory.name] = summary
        evaluation_path = directory / "evaluation_test.json"
        if evaluation_path.exists():
            reports[directory.name] = read_json(evaluation_path)

    (output_dir / "tab_model.tex").write_text(
        model_table(summaries, macros), encoding="utf-8"
    )
    (output_dir / "tab_results.tex").write_text(
        results_table(reports, macros), encoding="utf-8"
    )
    logger.info("tab_model.tex, tab_results.tex (%d runs, %d evaluations)",
                len(summaries), len(reports))

    primary = args.primary if args.primary in reports else (
        next(iter(reports), None)
    )
    if primary:
        (output_dir / "tab_errors.tex").write_text(
            error_table(reports[primary], macros, primary), encoding="utf-8"
        )
        (output_dir / "tab_examples.tex").write_text(
            examples_table(reports[primary]), encoding="utf-8"
        )
        macros.add("primary run", tex_escape(RUN_LABELS.get(primary, primary)))
        logger.info("tab_errors.tex, tab_examples.tex (from %s)", primary)
    else:
        for name in ("tab_errors.tex", "tab_examples.tex"):
            (output_dir / name).write_text(
                "\\textit{No evaluation results available yet.}\n", encoding="utf-8"
            )
        logger.warning("No evaluation reports; wrote placeholder tables.")

    # A single flag the report uses to switch between "results pending" and the
    # real discussion, so the document always compiles.
    macros.add("has results", "true" if reports else "false")

    (output_dir / "macros.tex").write_text(macros.render(), encoding="utf-8")
    logger.info("macros.tex (%d macros) -> %s", len(macros.entries), output_dir)


if __name__ == "__main__":
    main()
