def dataset_table(stats: dict, macros: MacroFile) -> str:
    splits = stats["splits"]
    rows = []
    for name in ("train", "validation", "test"):
        entry = splits[name]
        rows.append(
            f"{name.capitalize()} & {entry['pairs']:,} & "
            f"{entry['unique_en']:,} & {entry['unique_es']:,} & "
            f"{entry['length_words']['en']['mean']:.1f} & "
            f"{entry['length_words']['es']['mean']:.1f} & "
            f"{entry['length_subwords']['en']['mean']:.1f} & "
            f"{entry['length_subwords']['es']['mean']:.1f} \\\\"
        )
        macros.integer(f"pairs {name}", entry["pairs"])

    pairing = stats.get("pairing", {})
    cleaning = stats.get("cleaning", {})
    split = stats.get("split", {})

    macros.integer("tatoeba english sentences", pairing.get("english_sentences", 0))
    macros.integer("tatoeba spanish sentences", pairing.get("spanish_sentences", 0))
    macros.integer("tatoeba links scanned", pairing.get("links_scanned", 0))
    macros.integer("pairs raw", pairing.get("pairs_found", 0))
    macros.integer("pairs clean", cleaning.get("kept_pairs", 0))
    macros.number("retention percent", cleaning.get("retention_rate", 0) * 100, decimals=2)
    macros.integer("components", split.get("components", 0))
    macros.integer("leakage", sum(split.get("leakage_check", {}).values()))
    macros.integer("largest component", split.get("largest_component_pairs", 0))

    vocabulary = splits["train"]["vocabulary"]
    macros.integer("types en", vocabulary["en"]["types"])
    macros.integer("types es", vocabulary["es"]["types"])
    macros.number("type ratio", vocabulary["es"]["types"] / vocabulary["en"]["types"])
    macros.integer("tokens en", vocabulary["en"]["tokens"])
    macros.integer("tokens es", vocabulary["es"]["tokens"])
    macros.number("hapax en percent", vocabulary["en"]["hapax_fraction"] * 100, decimals=1)
    macros.number("hapax es percent", vocabulary["es"]["hapax_fraction"] * 100, decimals=1)

    oov = splits["test"]["word_oov"]
    macros.number("oov en percent", oov["en"]["unk_rate"] * 100, decimals=2)
    macros.number("oov es percent", oov["es"]["unk_rate"] * 100, decimals=2)

    macros.number("fertility en", splits["train"]["subword_fertility"]["en"])
    macros.number("fertility es", splits["train"]["subword_fertility"]["es"])
    macros.integer("subword vocab", stats["tokenizers"]["subword"]["vocab_size"])
    macros.integer("word vocab", stats["tokenizers"]["word"]["vocab_size"])

    return (
        "\\begin{tabular}{lrrrrrrr}\n"
        "\\toprule\n"
        "& & \\multicolumn{2}{c}{unique sentences} & "
        "\\multicolumn{2}{c}{mean words} & \\multicolumn{2}{c}{mean subwords} \\\\\n"
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\n"
        "Split & Pairs & EN & ES & EN & ES & EN & ES \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )


def model_table(summaries: dict[str, dict], macros: MacroFile) -> str:
    rows = []
    for run in RUN_ORDER:
        summary = summaries.get(run)
        if not summary:
            continue
        config = summary["config"]["model"]
        parameters = summary["parameters"]["total"]
        macros.integer(f"params {run}", parameters)
        macros.add(f"epochs {run}", summary.get("epochs_completed", "--"))

        if config["architecture"] == "transformer":
            geometry = (
                f"{config['num_encoder_layers']}+{config['num_decoder_layers']} layers, "
                f"$d_{{\\mathrm{{model}}}}={config['d_model']}$, "
                f"{config['num_heads']} heads"
            )
        else:
            geometry = (
                f"{config['lstm_num_layers']} layers, "
                f"hidden {config['lstm_hidden_size']}, bi-encoder"
            )

        rows.append(
            f"{RUN_LABELS.get(run, run)} & {config['vocab_size']:,} & "
            f"{config.get('embedding_dim') or config['d_model']} & "
            f"{geometry} & {parameters / 1e6:.1f}M \\\\"
        )

    if not rows:
        rows = ["\\multicolumn{5}{c}{\\itshape no trained runs found} \\\\"]

    return (
        "\\begin{tabular}{lrrlr}\n"
        "\\toprule\n"
        "System & Vocab & Emb. dim & Geometry & Params \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )


def results_table(reports: dict[str, dict], macros: MacroFile) -> str:
    rows = []
    for run in RUN_ORDER:
        report = reports.get(run)
        if not report:
            continue
        summary = report["summary"]
        values = []
        for direction in DIRECTIONS:
            bleu = summary["bleu"][direction]
            chrf = summary["chrf2"][direction]
            values.extend([f"{bleu:.2f}", f"{chrf:.2f}"])
            macros.number(f"bleu {run} {direction}", bleu)
            macros.number(f"chrf {run} {direction}", chrf)
        macros.number(f"bleu {run} mean", summary["mean_bleu"])
        rows.append(f"{RUN_LABELS.get(run, run)} & " + " & ".join(values) +
                    f" & {summary['mean_bleu']:.2f} \\\\")

    if not rows:
        rows = ["\\multicolumn{6}{c}{\\itshape no evaluations found} \\\\"]

    return (
        "\\begin{tabular}{lrrrrr}\n"
        "\\toprule\n"
        "& \\multicolumn{2}{c}{EN $\\rightarrow$ ES} & "
        "\\multicolumn{2}{c}{ES $\\rightarrow$ EN} & \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n"
        "System & BLEU & chrF2 & BLEU & chrF2 & Mean BLEU \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )


def error_table(report: dict, macros: MacroFile, run: str) -> str:
    categories: dict[str, dict[str, float]] = {}
    for direction in DIRECTIONS:
        analysis = report["directions"][direction]["error_analysis"]
        for name, rate in analysis["category_rates"].items():
            categories.setdefault(name, {})[direction] = rate * 100
        macros.number(
            f"mean sentence bleu {run} {direction}", analysis["mean_sentence_bleu"]
        )

    rows = []
    for name in sorted(categories, key=lambda n: -sum(categories[n].values())):
        values = " & ".join(
            f"{categories[name].get(direction, 0.0):.1f}\\%" for direction in DIRECTIONS
        )
        rows.append(f"\\texttt{{{tex_escape(name)}}} & {values} \\\\")
        for direction in DIRECTIONS:
            macros.number(
                f"error {run} {name} {direction}",
                categories[name].get(direction, 0.0), decimals=1,
            )

    if not rows:
        rows = ["\\multicolumn{3}{c}{\\itshape none} \\\\"]

    return (
        "\\begin{tabular}{lrr}\n"
        "\\toprule\n"
        "Failure mode & EN $\\rightarrow$ ES & ES $\\rightarrow$ EN \\\\\n"
        "\\midrule\n" + "\n".join(rows) + "\n"
        "\\bottomrule\n"
        "\\end{tabular}\n"
    )


def examples_table(report: dict, limit: int = 20) -> str:
    """The worst translations, formatted as a longtable for the appendix."""
    blocks = []
    for direction in DIRECTIONS:
        analysis = report["directions"][direction]["error_analysis"]
        arrow = ("EN $\\rightarrow$ ES" if direction == "en-es"
                 else "ES $\\rightarrow$ EN")
        rows = []
        for index, example in enumerate(analysis["worst"][:limit], start=1):
            rows.append(
                f"{index} & {example['sentence_bleu']:.1f} & "
                f"\\small {tex_escape(example['source'])} \\\\\n"
                f"& & \\small\\itshape ref: {tex_escape(example['reference'])} \\\\\n"
                f"& & \\small\\ttfamily out: {tex_escape(example['hypothesis'])} \\\\\n"
                f"& & \\scriptsize {tex_escape(', '.join(example['categories']))} \\\\"
                "\\addlinespace"
            )
        blocks.append(
            f"\\subsection*{{{arrow}}}\n"
            "\\begin{longtable}{@{}rp{0.7cm}p{11cm}@{}}\n"
            "\\toprule\n"
            "\\# & sBLEU & Source / reference / model output / failure modes \\\\\n"
            "\\midrule\n\\endhead\n" + "\n".join(rows) + "\n"
            "\\bottomrule\n\\end{longtable}\n"
        )
    return "\n".join(blocks)


